#!/usr/bin/env python3
"""Summarize what the dataset covers per company: OSFI portfolio, discount
curve and LICAT data by quarter, and which fiscal quarters have downloaded
documents. Writes data/coverage_summary.csv and COVERAGE.md.

Usage:
    python3 scripts/coverage_summary.py
"""
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
QUARTERS = [(y, f"Q{q}") for y in range(2020, 2027) for q in (1, 2, 3, 4)]
# October fiscal year ends: quarter ends Jan, Apr, Jul, Oct
OCT_YEAR_END = {"bmo_life", "rbc_life"}


def read(path):
    with open(os.path.join(DATA, path), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def doc_quarter(row):
    """(fiscal_year, 'Q1'..'Q4') for a document, or None if it can't be placed.
    Annual documents count as Q4."""
    year, period = row["fiscal_year"], row["period"]
    if year and period in ("Q1", "Q2", "Q3", "Q4"):
        return int(year), period
    if year and period == "FY":
        return int(year), "Q4"
    text = (row["url"].rsplit("/", 1)[-1] + " " + row["title"]).lower()
    if row["company_id"] in OCT_YEAR_END:
        m = re.search(r"-(20\d\d)(01|04|07|10)3[01]", text)  # bmo-20260731.htm
        if m:
            return int(m.group(1)), "Q" + str("01 04 07 10".split().index(m.group(2)) + 1)
    for pat, yq in ((r"q([1-4])[-_ ]?(20[2-3]\d)", lambda m: (m.group(2), m.group(1))),
                    (r"(?<![0-9])([1-4])q[-_ ]?(2\d)(?!\d)", lambda m: ("20" + m.group(2), m.group(1))),
                    (r"q([1-4])[-_]?(2\d)(?!\d)", lambda m: ("20" + m.group(2), m.group(1)))):
        m = re.search(pat, text)
        if m:
            y, q = yq(m)
            return int(y), "Q" + q
    if "40-f" in text or "annual" in text:
        return (int(year), "Q4") if year else None
    return None


def span(keys):
    """Sorted (year, quarter) set -> 'Q1 2023 to Q2 2026 (14)'."""
    if not keys:
        return "none"
    keys = sorted(keys)
    first, last = keys[0], keys[-1]
    return f"{first[1]} {first[0]} to {last[1]} {last[0]} ({len(keys)})"


def main():
    companies = read("companies.csv")
    osfi = {}

    def add(name, cid, year, quarter):
        osfi.setdefault(name, {}).setdefault(cid, set()).add((int(year), quarter))

    for r in read(os.path.join("osfi", "portfolio_mix.csv")):
        add("portfolio_" + r["basis"], r["company_id"], r["fiscal_year"], r["quarter"])
    for r in read(os.path.join("osfi", "licat_ratios.csv"))[1:]:  # second row holds addresses
        add("licat", r["company_id"], r["fiscal_year"], r["quarter"])
    for r in read(os.path.join("osfi", "discount_curves.csv")):
        add("discount_curve", r["company_id"], r["fiscal_year"], r["quarter"])

    docs, n_docs = {}, {}
    for r in read("document_index.csv"):
        if r["status"] != "ok":
            continue
        n_docs[r["company_id"]] = n_docs.get(r["company_id"], 0) + 1
        q = doc_quarter(r)
        if q and q in QUARTERS:
            docs.setdefault(r["company_id"], set()).add(q)

    years = sorted({y for y, _ in QUARTERS})
    out = []
    for c in companies:
        cid = c["company_id"]
        got = docs.get(cid, set())
        row = {"company_id": cid, "company": c["company"],
               "regulator": c["prudential_regulator"].split(" ")[0],
               "osfi_portfolio_ifrs4": span(osfi.get("portfolio_IFRS 4", {}).get(cid)),
               "osfi_portfolio_ifrs17": span(osfi.get("portfolio_IFRS 17", {}).get(cid)),
               "osfi_discount_curve": span(osfi.get("discount_curve", {}).get(cid)),
               "osfi_licat": span(osfi.get("licat", {}).get(cid)),
               "documents": n_docs.get(cid, 0)}
        for y, q in QUARTERS:
            row[f"{y}{q}"] = "x" if (y, q) in got else ""
        out.append(row)

    with open(os.path.join(DATA, "coverage_summary.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(out)

    def year_cell(r, y):
        marks = "".join(q[1] if r[f"{y}{q}"] else "·" for q in ("Q1", "Q2", "Q3", "Q4"))
        return "" if marks == "····" else marks

    lines = [
        "# Dataset coverage",
        "",
        "Generated by `scripts/coverage_summary.py`.",
        "",
        "## OSFI data",
        "",
        "First and last fiscal quarter in `data/osfi/` (number of quarters). Only OSFI-regulated companies "
        "appear; iA, Desjardins, Beneva, Humania and UV report to the AMF and Assumption Life to the FCNB.",
        "",
        "Breaks at the 2023 switch to IFRS 17 (fiscal 2024 for October year ends):",
        "",
        "- **Portfolio mix** (`portfolio_mix.csv`): 2020 to 2022 from the IFRS 4 return (10Q), 2023 on from LF1 "
        "and LF2. The main lines (cash, bonds, mortgages, shares, real estate, segregated funds, total assets) "
        "line up across the break. Policy loans exist only before 2023, because IFRS 17 moved them into insurance "
        "contract balances. The bond split by issuer and by investment grade exists only from 2023 "
        "(`invested_assets.csv`).",
        "- **Discount curves** exist only from 2023. IFRS 4 used CALM, which has no published discount curve, so "
        "the earlier blank is not a gap to fill.",
        "- **LICAT** runs back to 2018 without a gap, but the 2023 LICAT revision changed available capital for "
        "IFRS 17 (the contractual service margin now counts), so ratios before and after 2023 are not like for like.",
        "- BMO Life and RBC Life have no IFRS 4 rows for fiscal 2023 because their October year end put the "
        "switch at November 2023.",
        "",
        "| Company | Regulator | Portfolio mix, IFRS 4 | Portfolio mix, IFRS 17 | Discount curve | LICAT |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in out:
        lines.append(f"| {r['company']} | {r['regulator']} | {r['osfi_portfolio_ifrs4']} | "
                     f"{r['osfi_portfolio_ifrs17']} | {r['osfi_discount_curve']} | {r['osfi_licat']} |")
    lines += [
        "",
        "## Documents by fiscal quarter",
        "",
        "Each cell lists the quarters (1 to 4) with at least one downloaded document; `·` is a missing quarter "
        "and a blank cell means nothing for that year. Annual reports count as Q4, so annual-only reporters show "
        "`···4`. BMO and RBC use October year ends.",
        "",
        "| Company | Docs | " + " | ".join(str(y) for y in years) + " |",
        "| --- | ---: | " + " | ".join(":-:" for _ in years) + " |",
    ]
    for r in out:
        lines.append(f"| {r['company']} | {r['documents']} | " + " | ".join(year_cell(r, y) for y in years) + " |")
    with open(os.path.join(ROOT, "COVERAGE.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote data/coverage_summary.csv and COVERAGE.md for {len(out)} companies")


if __name__ == "__main__":
    main()
